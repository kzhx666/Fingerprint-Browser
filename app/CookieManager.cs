using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json;
using System.Threading.Tasks;

namespace KZManager;

/// <summary>
/// 13. Cookie 管理中心。
/// 支持 Netscape 与 JSON 格式 Cookie 的导入、导出、去重、清洗，
/// 以及通过 CDP Network.setCookies 真实沉淀进浏览器原生持久化数据库。
/// </summary>
public static class CookieManager
{
    public sealed class CookieItem
    {
        public string name { get; set; } = "";
        public string value { get; set; } = "";
        public string domain { get; set; } = "";
        public string path { get; set; } = "/";
        public double expires { get; set; } = -1;
        public bool httpOnly { get; set; }
        public bool secure { get; set; }
        public string sameSite { get; set; } = "Lax"; // Strict / Lax / None
    }

    /// <summary>解析 JSON 格式 Cookie 文本。</summary>
    public static List<CookieItem> ParseJson(string jsonText)
    {
        var list = new List<CookieItem>();
        try
        {
            using var doc = JsonDocument.Parse(jsonText);
            if (doc.RootElement.ValueKind != JsonValueKind.Array) return list;
            foreach (var el in doc.RootElement.EnumerateArray())
            {
                var it = new CookieItem();
                if (el.TryGetProperty("name", out var n)) it.name = n.GetString() ?? "";
                if (el.TryGetProperty("value", out var v)) it.value = v.GetString() ?? "";
                if (el.TryGetProperty("domain", out var d)) it.domain = d.GetString() ?? "";
                if (el.TryGetProperty("path", out var p)) it.path = p.GetString() ?? "/";
                if (el.TryGetProperty("expirationDate", out var exp)) it.expires = exp.GetDouble();
                else if (el.TryGetProperty("expires", out var exp2)) it.expires = exp2.GetDouble();
                if (el.TryGetProperty("httpOnly", out var ho)) it.httpOnly = ho.GetBoolean();
                if (el.TryGetProperty("secure", out var sc)) it.secure = sc.GetBoolean();
                if (el.TryGetProperty("sameSite", out var ss)) it.sameSite = ss.GetString() ?? "Lax";
                if (!string.IsNullOrEmpty(it.name) && !string.IsNullOrEmpty(it.domain))
                    list.Add(it);
            }
        }
        catch { }
        return Deduplicate(list);
    }

    /// <summary>解析 Netscape 格式 Cookie 文本 (制表符分隔)。</summary>
    public static List<CookieItem> ParseNetscape(string netscapeText)
    {
        var list = new List<CookieItem>();
        var lines = netscapeText.Split(new[] { '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries);
        foreach (var l in lines)
        {
            var line = l.Trim();
            if (line.Length == 0 || line.StartsWith("# HttpOnly_") == false && line.StartsWith("#")) continue;

            bool isHttpOnly = false;
            if (line.StartsWith("# HttpOnly_"))
            {
                isHttpOnly = true;
                line = line.Substring(11).Trim();
            }

            var parts = line.Split('\t');
            if (parts.Length < 7) continue;

            var it = new CookieItem
            {
                domain = parts[0].Trim(),
                path = parts[2].Trim(),
                secure = string.Equals(parts[3].Trim(), "TRUE", StringComparison.OrdinalIgnoreCase),
                httpOnly = isHttpOnly,
                name = parts[5].Trim(),
                value = parts[6].Trim()
            };
            if (double.TryParse(parts[4].Trim(), out var exp)) it.expires = exp;
            if (!string.IsNullOrEmpty(it.name) && !string.IsNullOrEmpty(it.domain))
                list.Add(it);
        }
        return Deduplicate(list);
    }

    /// <summary>按 (domain, path, name) 唯一键去重。</summary>
    public static List<CookieItem> Deduplicate(IEnumerable<CookieItem> items)
    {
        var map = new Dictionary<string, CookieItem>(StringComparer.OrdinalIgnoreCase);
        foreach (var it in items)
        {
            var key = $"{it.domain}|{it.path}|{it.name}";
            map[key] = it; // 后来者覆盖
        }
        return map.Values.ToList();
    }

    /// <summary>导出为 Netscape 格式文本。</summary>
    public static string ExportNetscape(IEnumerable<CookieItem> items)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Netscape HTTP Cookie File");
        sb.AppendLine("# Generated by KZManager");
        foreach (var c in items)
        {
            var prefix = c.httpOnly ? "# HttpOnly_" : "";
            var subdomains = c.domain.StartsWith(".") ? "TRUE" : "FALSE";
            var sec = c.secure ? "TRUE" : "FALSE";
            long exp = c.expires > 0 ? (long)c.expires : 2147483647;
            sb.AppendLine($"{prefix}{c.domain}\t{subdomains}\t{c.path}\t{sec}\t{exp}\t{c.name}\t{c.value}");
        }
        return sb.ToString();
    }

    /// <summary>导出为 JSON 格式文本。</summary>
    public static string ExportJson(IEnumerable<CookieItem> items)
        => JsonSerializer.Serialize(items, new JsonSerializerOptions { WriteIndented = true });

    /// <summary>通过 CDP 接口将 Cookie 真实注入已启动的实例。</summary>
    public static async Task<(bool ok, int injected, string error)> InjectViaCdpAsync(int cdpPort, List<CookieItem> cookies)
    {
        if (cookies.Count == 0) return (true, 0, "");
        try
        {
            using var hc = new System.Net.Http.HttpClient { Timeout = TimeSpan.FromSeconds(6) };
            var listJson = await hc.GetStringAsync($"http://127.0.0.1:{cdpPort}/json/list");
            using var listDoc = JsonDocument.Parse(listJson);
            string? wsUrl = null;
            foreach (var el in listDoc.RootElement.EnumerateArray())
            {
                if (el.TryGetProperty("type", out var ty) && ty.GetString() == "page" &&
                    el.TryGetProperty("webSocketDebuggerUrl", out var wsProp))
                {
                    wsUrl = wsProp.GetString();
                    if (!string.IsNullOrEmpty(wsUrl)) break;
                }
            }
            if (string.IsNullOrEmpty(wsUrl))
                return (false, 0, "未连接到 CDP 调试端点");

            using var ws = new System.Net.WebSockets.ClientWebSocket();
            using var cts = new System.Threading.CancellationTokenSource(TimeSpan.FromSeconds(25));
            await ws.ConnectAsync(new Uri(wsUrl), cts.Token);

            var req = JsonSerializer.Serialize(new {
                id = 999,
                method = "Network.setCookies",
                @params = new { cookies }
            });
            var bytes = Encoding.UTF8.GetBytes(req);
            await ws.SendAsync(new ArraySegment<byte>(bytes), System.Net.WebSockets.WebSocketMessageType.Text, true, cts.Token);
            await Task.Delay(1000, cts.Token);
            await ws.CloseAsync(System.Net.WebSockets.WebSocketCloseStatus.NormalClosure, "done", System.Threading.CancellationToken.None);
            return (true, cookies.Count, "");
        }
        catch (Exception e)
        {
            return (false, 0, "CDP 注入异常: " + (e.InnerException?.Message ?? e.Message));
        }
    }
}
